import json
import re
from typing import List, Optional
from core.config import get_settings
from core.logger import setup_logger
from llm.base import BaseLLMProvider, LLMMessage
from llm.ollama_provider import OllamaProvider
from llm.groq_provider import GroqProvider
from tasks.models import RiskLevel, TaskStep

logger = setup_logger("TaskPlanner")
settings = get_settings()

PLANNER_SYSTEM_PROMPT = """You are the Lead Task Planner of JARVIS AI Agent.
Your job is to break down a user's goal into strict execution steps using ONLY registered tools.

EXPECTED JSON STEP SCHEMA:
Each step object MUST contain these exact keys:
- "id": integer (1, 2, 3...)
- "title": short string title
- "description": detailed string description
- "tool_name": exact name of the tool to use, or "reasoning" for pure logic
- "parameters": dictionary of parameters for the tool
- "risk_level": "low", "medium", or "high"
- "requires_approval": boolean (true if risk_level is high)
- "verification_method": "syntax_check", "test_pass", "output_check", or "none"

REGISTERED TOOLS & PARAMETERS:
- "directory_create": {"dir_path": "<path>"}
- "file_write": {"file_path": "<path>", "content": "<text>"}
- "file_read": {"file_path": "<path>"}
- "directory_scan": {"dir_path": "<path>"}
- "python_execute": {"file_path": "<path>"}
- "terminal_execute": {"command": "<cmd>"}
- "system_info": {}
- "syntax_check": {"file_path": "<path>"}
- "test_runner": {"test_target": "<target>"}
- "app_launcher": {"target": "<app_name>"}
- "universal_launcher": {"target": "<app_name>"}
- "web_search": {"query": "<search_query>"}
- "deep_web_reader": {"url": "<url>"}
- "system_hardware_control": {"action": "volume_up|volume_down|volume_set|volume_mute|brightness_set", "value": <int>}
- "window_manager": {"action": "list_windows|focus_window", "target_title": "<app_name>"}
- "toast_notification": {"title": "<title>", "message": "<msg>"}
- "process_kill": {"target": "<process_name>"}
- "screen_capture": {"output_file": "<path>"}
- "docker_control": {"action": "ps|up|down|logs|build"}
- "git_control": {"action": "status|log|add|commit|checkout"}
- "reasoning": {}

REPLY ONLY WITH A VALID JSON ARRAY OF STEP OBJECTS."""


class TaskPlanner:
    def __init__(self, provider: Optional[BaseLLMProvider] = None):
        self.provider = provider or OllamaProvider(default_model=settings.DEFAULT_CHAT_MODEL)

    async def create_plan(self, goal: str, context: Optional[str] = None) -> List[TaskStep]:
        prompt_content = f"Goal: {goal}"
        if context:
            prompt_content += f"\nContext: {context}"

        messages = [
            LLMMessage(role="system", content=PLANNER_SYSTEM_PROMPT),
            LLMMessage(role="user", content=prompt_content),
        ]

        try:
            response = await self.provider.chat(messages=messages, temperature=0.1)
            raw_text = response.content.strip()

            json_match = re.search(r"\[.*\]", raw_text, re.DOTALL)
            if json_match:
                raw_text = json_match.group(0)

            steps_data = json.loads(raw_text)
            steps: List[TaskStep] = []

            for idx, item in enumerate(steps_data, 1):
                risk = str(item.get("risk_level", "low")).lower()
                if risk not in ["low", "medium", "high"]:
                    risk = "low"

                tool_n = item.get("tool_name", "reasoning")
                if not tool_n or not isinstance(tool_n, str):
                    tool_n = "reasoning"

                step = TaskStep(
                    id=idx,
                    title=item.get("title", f"Step {idx}"),
                    description=item.get("description", ""),
                    tool_name=tool_n,
                    parameters=item.get("parameters", {}),
                    risk_level=RiskLevel(risk),
                    requires_approval=item.get("requires_approval", (risk == "high")),
                    verification_method=item.get("verification_method", "none"),
                )
                steps.append(step)

            if steps:
                return steps

            raise ValueError("Empty steps generated by LLM")
        except Exception as e:
            logger.warning(f"TaskPlanner fallback engaged: {e}")
            return self._fallback_plan(goal)

    def _fallback_plan(self, goal: str) -> List[TaskStep]:
        return [
            TaskStep(
                id=1,
                title="Goal Analysis",
                description=f"Goal: {goal}",
                tool_name="reasoning",
                risk_level=RiskLevel.LOW,
            ),
            TaskStep(
                id=2,
                title="Environment Audit",
                description="Inspecting target workspace environment",
                tool_name="directory_scan",
                parameters={"dir_path": "."},
                risk_level=RiskLevel.LOW,
            )
        ]
